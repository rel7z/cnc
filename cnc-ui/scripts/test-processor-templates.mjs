import fs from "node:fs";
import assert from "node:assert/strict";
import {blankDefinition,parseProcessorTemplates,serializeProcessorTemplates} from "../lib/processor-editor.ts";
const read=name=>fs.readFileSync(new URL("../../processor/examples/"+name,import.meta.url),"utf8");
const raw=read("all-tools.template.json");
const parsed=parseProcessorTemplates(raw,blankDefinition());
assert.deepEqual(parsed.definitions.map(d=>[d.tool_id,d.incoming,d.folder]),[["divi","divi.txt","tools/divi"],["bf","wordpress.txt","tools/bf"]]);
assert.equal(parsed.definitions[0].manifest.scripts.scanner.outputs[0].send_to,"checker");
assert.equal(parsed.definitions[0].manifest.scripts.checker.input,"results.txt");
assert.equal(parsed.definitions[1].manifest.scripts.scanner.runtime,"binary");
assert.equal(parsed.definitions[1].manifest.scripts.scanner.path,"rr");
assert.deepEqual(parseProcessorTemplates(serializeProcessorTemplates(parsed.name,parsed.definitions),blankDefinition()),parsed);
const duplicate=JSON.parse(raw);duplicate.definitions.push(duplicate.definitions[0]);
assert.throws(()=>parseProcessorTemplates(JSON.stringify(duplicate),blankDefinition()),/duplicate tool ID/);
const bad=JSON.parse(raw);bad.definitions[1].manifest.scripts.scanner.runtime="";
assert.throws(()=>parseProcessorTemplates(JSON.stringify(bad),blankDefinition()),/runtime/);
const empty=JSON.parse(raw);empty.definitions=[];
assert.throws(()=>parseProcessorTemplates(JSON.stringify(empty),blankDefinition()),/1–32/);
for(const name of ["divi","bf"])assert.equal(parseProcessorTemplates(read(name+".template.json"),blankDefinition()).definitions.length,1);
console.log("PASS: combined roundtrip, independent routes/folders, chain, binary, duplicate/invalid rejection, legacy single templates.");
